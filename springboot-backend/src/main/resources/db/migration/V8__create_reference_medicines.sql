-- ============================================
-- Reference Medicines table (global drug database)
-- Used as fallback matching layer when user's local
-- medicine inventory doesn't have a match
-- ============================================
CREATE TABLE IF NOT EXISTS reference_medicines (
    id SERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    category VARCHAR(50),
    spec VARCHAR(200),
    manufacturer VARCHAR(200),
    dosage VARCHAR(200),
    is_otc BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ref_medicines_name ON reference_medicines(name);
CREATE INDEX IF NOT EXISTS idx_ref_medicines_category ON reference_medicines(category);

